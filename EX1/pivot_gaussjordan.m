function [x, A_inv, dx, dr, cond_A] = pivot_gaussjordan(A, b, x_exact)
    n = size(A, 1);
    
    % Βήμα 2: Δημιουργία επαυξημένου πίνακα. 
    % Κολλάμε τον b και τον Ταυτοτικό πίνακα I για να βρούμε και τον A^-1 (μέθοδος Jordan)
    a = [A, b, eye(n)]; 
    
    % Βήμα 3: Αρχικοποίηση διανύσματος οδήγησης h
    h = (1:n)';
    
    % Αριθμός συνθήκης
    cond_A = cond(A);
    
    % Βήμα 4: Gauss-Jordan με μερική οδήγηση
    for r = 1:n
        % Εύρεση μέγιστου στοιχείου στη στήλη r (από τη γραμμή r και κάτω)
        [~, max_idx] = max(abs(a(h(r:n), r)));
        p = max_idx + r - 1; 
        
        % Έλεγχος αν το μέγιστο είναι 0
        if a(h(p), r) == 0
            error('Δεν υπάρχει μοναδική λύση (ιδιόμορφος πίνακας).');
        end
        
        % Ανταλλαγή γραμμών (δεικτών)
        if p ~= r
            temp = h(r);
            h(r) = h(p);
            h(p) = temp;
        end
        
        % Απαλοιφή Gauss-Jordan (μηδενισμός ΚΑΙ πάνω ΚΑΙ κάτω από τη διαγώνιο)
        for i = 1:n
            if i ~= r
                m = -a(h(i), r) / a(h(r), r);
                a(h(i), :) = a(h(i), :) + m * a(h(r), :);
            end
        end
    end
    
    % Βήμα 5: Κανονικοποίηση (διαίρεση της κάθε γραμμής με τον οδηγό της)
    for i = 1:n
        a(h(i), :) = a(h(i), :) / a(h(i), i);
    end
    
    % Εξαγωγή της λύσης (στήλη n+1) και του Αντιστρόφου (στήλες n+2 έως το τέλος)
    x = a(h, n+1);
    A_inv = a(h, n+2:end);
    
    % Υπολογισμός σφαλμάτων βάσει του πίνακα της εκφώνησης
    dx = norm(x_exact - x, inf);      % Απόλυτο σφάλμα ||δx||_inf
    dr = norm(b - A * x, inf);        % Υπόλοιπο ||δr||_inf
end